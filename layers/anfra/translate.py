"""Translate model/tpch.ossie.yaml into AML (anfra / AMQL) mechanically.

  uv run python layers/anfra/translate.py

OSSIE dataset -> AML Model (one per file), OSSIE field -> dimension, OSSIE relationship -> AML Relationship (composite keys via `on {}`), OSSIE metric -> dataset metric. The physical key columns the relationships and primary keys use but the model does not declare as fields become hidden dimensions (AML joins on dimensions); queries never reference them.
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent.parent
OUT = Path(__file__).resolve().parent / "project"
TYPES = {"Date": "date", "String": "text", "Decimal": "number", "Integer": "number"}

# OSSIE metric SQL -> AQL. Same aggregation over the same declared fields (or join keys).
METRICS = {
    "revenue": "lineitem | sum(lineitem.extended_price * (1 - lineitem.discount))",
    "gross_sales": "lineitem | sum(lineitem.extended_price)",
    "total_quantity": "lineitem | sum(lineitem.quantity)",
    "line_count": "lineitem | count(lineitem.l_orderkey)",
    "avg_discount": "lineitem | avg(lineitem.discount)",
    "order_count": "orders | count(orders.order_key)",
    "order_value": "orders | sum(orders.total_price)",
    "avg_order_value": "(orders | sum(orders.total_price)) / (orders | count(orders.order_key))",
    "customer_count": "customer | count_distinct(customer.customer_key)",
    "total_available_qty": "partsupp | sum(partsupp.available_qty)",
    "supplier_count": "supplier | count_distinct(supplier.supplier_key)",
}


def q(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main():
    m = yaml.safe_load((ROOT / "model/tpch.ossie.yaml").read_text())["semantic_model"][0]
    ds = {d["name"]: d for d in m["datasets"]}
    col2field = {n: {f["expression"]["dialects"][0]["expression"]: f["name"] for f in d["fields"]}
                 for n, d in ds.items()}
    keys = {n: list(d["primary_key"]) for n, d in ds.items()}
    for r in m["relationships"]:
        keys[r["from"]] += r["from_columns"]
        keys[r["to"]] += r["to_columns"]

    def ref(model, col):
        return f"r({model}.{col2field[model].get(col, col)})"

    (OUT / "models").mkdir(parents=True, exist_ok=True)
    (OUT / "datasets").mkdir(parents=True, exist_ok=True)
    for n, d in ds.items():
        pk = d["primary_key"]
        lines = [f"// Generated by layers/anfra/translate.py from model/tpch.ossie.yaml dataset `{n}`.",
                 f"Model {n} {{", "  type: 'table'", f"  label: {q(n)}",
                 f"  description: {q(d.get('description', ''))}", "  data_source_name: 'tpch'",
                 f"  table_name: {q(d['source'].split('.')[-1])}"]

        def dim(name, col, typ, desc, hidden=False):
            lines.extend(["", f"  dimension {name} {{", f"    label: {q(name)}", f"    type: {q(typ)}"])
            if hidden:
                lines.append("    hidden: true")
            if desc:
                lines.append(f"    description: {q(desc)}")
            if len(pk) == 1 and col == pk[0]:
                lines.append("    primary_key: true")
            lines.extend([f"    definition: @sql {{{{ #SOURCE.{col} }}}};;", "  }"])

        for f in d["fields"]:
            dim(f["name"], f["expression"]["dialects"][0]["expression"], TYPES[f["datatype"]],
                f.get("description"))
        for col in dict.fromkeys(keys[n]):
            if col not in col2field[n]:
                dim(col, col, "number", "Key column used by an OSSIE relationship or primary key; "
                    "not a model member.", hidden=True)
        lines.append("}")
        (OUT / "models" / f"{n}.model.aml").write_text("\n".join(lines) + "\n")

    rels = []
    for r in m["relationships"]:
        f, t = r["from"], r["to"]
        pairs = list(zip(r["from_columns"], r["to_columns"]))
        lines = [f"Relationship {r['name']} {{", "  type: 'many_to_one'",
                 f"  from: {ref(f, pairs[0][0])}", f"  to: {ref(t, pairs[0][1])}"]
        for fc, tc in pairs[1:]:
            lines.append(f"  on {{ from: {ref(f, fc)} to: {ref(t, tc)} }}")
        lines.append("}")
        rels.append("\n".join(lines))
    (OUT / "datasets" / "relationships.aml").write_text(
        "// Generated by layers/anfra/translate.py: the 11 OSSIE relationships.\n"
        + "\n\n".join(rels) + "\n")

    assert set(METRICS) == {x["name"] for x in m["metrics"]}
    lines = ["// Generated by layers/anfra/translate.py: the shared OSSIE model as one AML dataset.",
             f"Dataset {m['name']} {{", f"  label: {q(m['name'])}",
             f"  description: {q(m.get('description', ''))}", "  data_source_name: 'tpch'",
             f"  models: [{', '.join(ds)}]", "  relationships: ["]
    lines += [f"    relationship({r['name']}, true)," for r in m["relationships"]]
    lines.append("  ]")
    for x in m["metrics"]:
        lines += ["", f"  metric {x['name']} {{", f"    label: {q(x['name'])}", "    type: 'number'",
                  f"    description: {q(x.get('description', ''))}",
                  f"    definition: @aql {METRICS[x['name']]};;", "  }"]
    lines.append("}")
    (OUT / "datasets" / "tpch.dataset.aml").write_text("\n".join(lines) + "\n")
    print("wrote", len(ds), "models,", len(rels), "relationships,", len(METRICS), "metrics")


if __name__ == "__main__":
    main()
